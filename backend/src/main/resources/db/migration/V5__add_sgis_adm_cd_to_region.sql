-- ============================================================================
-- REGION에 SGIS 원본 adm_cd를 별도 컬럼으로 추가한다.
--
-- 실제 두 API를 라이브로 호출해 대조한 결과, SGIS adm_cd와 상권정보 adongCd는
-- 같은 지역이어도 다른 코드값이다 - 예: 강남구 역삼1동의 경우
--   SGIS adm_cd(자체 시군구 코드 11230 사용)   = 11230640
--   상권정보 adongCd(행정표준코드 11680 사용) = 11680640
-- 동 단위 접미(640/650 등)는 같아도 시군구 5자리 prefix가 서로 다른 번호체계다.
-- 그래서 REGION.region_code(상권정보 표준 adongCd, 프론트/타 공공데이터와 연동하기
-- 쉬운 코드)를 그대로 PK로 쓰고, SGIS 쪽 코드는 population_stat 조회에 필요하므로
-- 별도 컬럼(sgis_adm_cd)에 보관한다. 두 코드를 같은 문자열로 가정하고 비교하던
-- 기존 매핑 검증 로직은 폐기하고, 이 컬럼으로 명시적 대응 관계를 저장한다.
-- ============================================================================
ALTER TABLE region
    ADD COLUMN sgis_adm_cd VARCHAR(10);
